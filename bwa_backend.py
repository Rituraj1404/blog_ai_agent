WORKER_SYSTEM = """You are a senior technical writer and developer advocate.
Write ONE section of a technical blog post in Markdown.

Constraints:
- Cover ALL bullets in order.
- Target words ±15%.
- Output only section markdown starting with "## <Section Title>".

Scope guard:
- If blog_kind=="news_roundup", do NOT drift into tutorials (scraping/RSS/how to fetch).
  Focus on events + implications.

Grounding:
- If mode=="open_book": do not introduce any specific event/company/model/funding/policy claim unless supported by provided Evidence URLs.
  For each supported claim, attach a Markdown link ([Source](URL)).
  If unsupported, write "Not found in provided sources."
- If requires_citations==true (hybrid tasks): cite Evidence URLs for external claims.

Code:
- If requires_code==true, include at least one minimal snippet.
"""

async def worker_node(payload: dict) -> dict:
    task = Task(**payload["task"])
    plan = Plan(**payload["plan"])
    evidence = [EvidenceItem(**e) for e in payload.get("evidence", [])]

    bullets_text = "\n- " + "\n- ".join(task.bullets)
    evidence_text = "\n".join(
        f"- {e.title} | {e.url} | {e.published_at or 'date:unknown'}"
        for e in evidence[:20]
    )

    section_md = (await llm.ainvoke(
        [
            SystemMessage(content=WORKER_SYSTEM),
            HumanMessage(
                content=(
                    f"Blog title: {plan.blog_title}\n"
                    f"Audience: {plan.audience}\n"
                    f"Tone: {plan.tone}\n"
                    f"Blog kind: {plan.blog_kind}\n"
                    f"Constraints: {plan.constraints}\n"
                    f"Topic: {payload['topic']}\n"
                    f"Mode: {payload.get('mode')}\n"
                    f"As-of: {payload.get('as_of')} (recency_days={payload.get('recency_days')})\n\n"
                    f"Section title: {task.title}\n"
                    f"Goal: {task.goal}\n"
                    f"Target words: {task.target_words}\n"
                    f"Tags: {task.tags}\n"
                    f"requires_research: {task.requires_research}\n"
                    f"requires_citations: {task.requires_citations}\n"
                    f"requires_code: {task.requires_code}\n"
                    f"Bullets:{bullets_text}\n\n"
                    f"Evidence (ONLY cite these URLs):\n{evidence_text}\n"
                )
            ),
        ]
    )).content.strip()

    return {"sections": [(task.id, sanitize_md(section_md))]}

# ============================================================
# 8) ReducerWithImages (subgraph)
#    merge_content -> decide_images -> generate_and_place_images
# ============================================================
def merge_content(state: State) -> dict:
    plan = state["plan"]
    if plan is None:
        raise ValueError("merge_content called without plan.")
    ordered_sections = [md for _, md in sorted(state["sections"], key=lambda x: x[0])]
    body = sanitize_md("\n\n".join(ordered_sections).strip())
    merged_md = f"# {plan.blog_title}\n\n{body}\n"
    return {"merged_md": merged_md}


DECIDE_IMAGES_SYSTEM = """You are an expert technical editor.
Decide if images/diagrams are needed for THIS blog.

Rules:
- Max 3 images total.
- Each image must materially improve understanding (diagram/flow/table-like visual).
- Insert placeholders exactly: [[IMAGE_1]], [[IMAGE_2]], [[IMAGE_3]].
- If no images needed: md_with_placeholders must equal input and images=[].
- Avoid decorative images; prefer technical diagrams with short labels.
Return strictly GlobalImagePlan.
"""

def decide_images(state: State) -> dict:
    planner = llm.with_structured_output(GlobalImagePlan)
    merged_md = state["merged_md"]
    plan = state["plan"]
    assert plan is not None

    image_plan = planner.invoke(
        [
            SystemMessage(content=DECIDE_IMAGES_SYSTEM),
            HumanMessage(
                content=(
                    f"Blog kind: {plan.blog_kind}\n"
                    f"Topic: {state['topic']}\n\n"
                    "Insert placeholders + propose image prompts.\n\n"
                    f"{merged_md}"
                )
            ),
        ]
    )

    return {
        "md_with_placeholders": image_plan.md_with_placeholders,
        "image_specs": [img.model_dump() for img in image_plan.images],
    }


def _ddg_image_search(query: str, max_results: int = 10) -> List[str]:
    """
    Search DuckDuckGo Images and return a list of direct image URLs.
    No API key needed — uses DDG's JSON endpoint.
    """
    import urllib.parse
    import urllib.request
    import json

    # Step 1: get vqd token (required by DDG)
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                      "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
        "Accept-Language": "en-US,en;q=0.9",
    }
    search_url = f"https://duckduckgo.com/?q={urllib.parse.quote(query)}&iax=images&ia=images"
    try:
        req = urllib.request.Request(search_url, headers=headers)
        with urllib.request.urlopen(req, timeout=10) as resp:
            html = resp.read(50_000).decode("utf-8", errors="ignore")
    except Exception as e:
        print(f"[image_search] DDG token fetch failed: {e}")
        return []

    # Extract vqd token
    vqd_match = re.search(r'vqd=([\d-]+)', html)
    if not vqd_match:
        vqd_match = re.search(r'"vqd":"([^"]+)"', html)
    if not vqd_match:
        print("[image_search] Could not extract vqd token from DDG")
        return []
    vqd = vqd_match.group(1)

    # Step 2: fetch image results JSON
    params = urllib.parse.urlencode({
        "l": "us-en",
        "o": "json",
        "q": query,
        "vqd": vqd,
        "f": ",,,,,",
        "p": "1",
    })
    img_api_url = f"https://duckduckgo.com/i.js?{params}"
    try:
        req = urllib.request.Request(img_api_url, headers={**headers, "Referer": search_url})
        with urllib.request.urlopen(req, timeout=10) as resp:
            data = json.loads(resp.read().decode("utf-8", errors="ignore"))
    except Exception as e:
        print(f"[image_search] DDG image JSON fetch failed: {e}")
        return []

    urls = []
    for item in data.get("results", [])[:max_results]:
        img_url = item.get("image") or item.get("thumbnail")
        if img_url and img_url.startswith("http"):
            urls.append(img_url)
    return urls


def _download_image(url: str) -> Optional[bytes]:
    """Download an image from a URL; return bytes or None on failure."""
    import urllib.request
    headers = {
        "User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
                      "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36",
    }
    try:
        req = urllib.request.Request(url, headers=headers)
        with urllib.request.urlopen(req, timeout=15) as resp:
            content_type = resp.headers.get("Content-Type", "")
            if not any(t in content_type for t in ("image/", "application/octet")):
                return None
            data = resp.read()
        return data if len(data) > 2000 else None
    except Exception:
        return None


def _fetch_image_for_spec(query: str) -> Optional[bytes]:
    """
    Search DDG Images for `query`, try downloading each result until one succeeds.
    Returns image bytes or None.
    """
    print(f"[image] Searching DDG Images for: {query!r}")
    urls = _ddg_image_search(query, max_results=10)
    if not urls:
        print("[image] No URLs returned from DDG image search.")
        return None
    for url in urls:
        data = _download_image(url)
        if data:
            print(f"[image] Downloaded from {url}")
            return data
    print("[image] All DDG image URLs failed to download.")
    return None


def _safe_slug(title: str) -> str:
    s = title.strip().lower()
    s = re.sub(r"[^a-z0-9 _-]+", "", s)
    s = re.sub(r"\s+", "_", s).strip("_")
    return s or "blog"


def generate_and_place_images(state: State) -> dict:
    plan = state["plan"]
    assert plan is not None

    md = state.get("md_with_placeholders") or state["merged_md"]
    image_specs = state.get("image_specs", []) or []

    # If no images requested, just write merged markdown
    if not image_specs:
        filename = f"{_safe_slug(plan.blog_title)}.md"
        Path(filename).write_text(md, encoding="utf-8")
        return {"final": md}

    images_dir = Path("images")
    images_dir.mkdir(exist_ok=True)

    def _process_spec(spec: dict) -> tuple[str, str]:
        """Returns (placeholder, replacement_md). Runs in a thread."""
        placeholder = spec["placeholder"]
        out_path = images_dir / spec["filename"]

        if not out_path.exists():
            search_query = f"{spec.get('alt', '')} {spec.get('caption', '')}".strip()
            if not search_query:
                search_query = spec.get("prompt", "")[:120]
            try:
                img_bytes = _fetch_image_for_spec(search_query)
                if img_bytes is None:
                    raise RuntimeError("No image found via DDG image search.")
                out_path.write_bytes(img_bytes)
            except Exception as e:
                fallback = (
                    f"> **[IMAGE NOT FOUND]** {spec.get('caption','')}\n>\n"
                    f"> **Alt:** {spec.get('alt','')}\n>\n"
                    f"> **Search query:** {search_query}\n>\n"
                    f"> **Error:** {e}\n"
                )
                return placeholder, fallback

        return placeholder, f"![{spec['alt']}](images/{spec['filename']})\n*{spec['caption']}*"

    # Fix 2: fetch all images in parallel
    with concurrent.futures.ThreadPoolExecutor(max_workers=3) as ex:
        futures = [ex.submit(_process_spec, spec) for spec in image_specs]
        for fut in concurrent.futures.as_completed(futures):
            placeholder, replacement = fut.result()
            md = md.replace(placeholder, replacement)

    filename = f"{_safe_slug(plan.blog_title)}.md"
    Path(filename).write_text(md, encoding="utf-8")
    return {"final": md}

# build reducer subgraph
reducer_graph = StateGraph(State)
reducer_graph.add_node("merge_content", merge_content)
reducer_graph.add_node("decide_images", decide_images)
reducer_graph.add_node("generate_and_place_images", generate_and_place_images)
reducer_graph.add_edge(START, "merge_content")
reducer_graph.add_edge("merge_content", "decide_images")
reducer_graph.add_edge("decide_images", "generate_and_place_images")
reducer_graph.add_edge("generate_and_place_images", END)
reducer_subgraph = reducer_graph.compile()

# -----------------------------
# 9) Build main graph
# -----------------------------
g = StateGraph(State)
g.add_node("router", router_node)
g.add_node("research", research_node)
g.add_node("orchestrator", orchestrator_node)
g.add_node("worker", worker_node)
g.add_node("reducer", reducer_subgraph)

g.add_edge(START, "router")
g.add_conditional_edges("router", route_next, {"research": "research", "orchestrator": "orchestrator"})
g.add_edge("research", "orchestrator")

g.add_conditional_edges("orchestrator", fanout, ["worker"])
g.add_edge("worker", "reducer")
g.add_edge("reducer", END)

app = g.compile()
